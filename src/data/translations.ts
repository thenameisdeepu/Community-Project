export function translateTime(time: string, lang: Language): string {
  if (!time) return '';
  if (lang === 'kn') {
    if (timeTranslationsKn[time]) return timeTranslationsKn[time];
    // Dynamic patterns: '28m ago', '2h ago', '3 days ago'
    const knDigits = ['೦', '೧', '೨', '೩', '೪', '೫', '೬', '೭', '೮', '೯'];
    const toKn = (s: string) => s.replace(/\d/g, (d) => knDigits[parseInt(d, 10)]);

    const mMatch = time.match(/^(\d+)\s*m\s*ago$/i);
    if (mMatch) return `${toKn(mMatch[1])} ನಿಮಿಷಗಳ ಹಿಂದೆ`;

    const hMatch = time.match(/^(\d+)\s*h\s*ago$/i);
    if (hMatch) return `${toKn(hMatch[1])} ಗಂಟೆಗಳ ಹಿಂದೆ`;

    const dMatch = time.match(/^(\d+)\s*days?\s*ago$/i);
    if (dMatch) return `${toKn(dMatch[1])} ದಿನಗಳ ಹಿಂದೆ`;

    if (time.toLowerCase() === 'just now') return 'ಈಗಷ್ಟೇ';
    if (time.toLowerCase() === 'yesterday') return 'ನಿನ್ನೆ';
    return toKn(time);
  }
  return time;
}

export function translateIssueTitle(issue: { title: string; titleKn?: string }, lang: Language): string {
  if (!issue || !issue.title) return '';
  if (lang === 'kn') {
    if (issue.titleKn) return issue.titleKn;
    if (issueTitlesKn[issue.title]) return issueTitlesKn[issue.title];
    // Check for partial keyword matches
    for (const [enKey, knVal] of Object.entries(issueTitlesKn)) {
      if (issue.title.toLowerCase().includes(enKey.toLowerCase()) || enKey.toLowerCase().includes(issue.title.toLowerCase())) {
        return knVal;
      }
    }
    return issue.title;
  }
  return issue.title;
}

